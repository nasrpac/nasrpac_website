#!/usr/bin/env python3
"""Bundle hero3d.js + Three.js into one classic script (hero3d.bundle.js).

Why: browsers block ES modules and image textures on file:// pages, so the
3D hero would silently fall back to SVG when index.html is double-clicked.
A single non-module script with the logo embedded works everywhere.

Run from the project root after editing hero3d.js:
    python3 tools/build-hero.py
Needs Pillow (pip install pillow) to embed a 256px copy of logo.png.
"""
import base64, io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(ROOT, 'vendor')
read = lambda p: open(os.path.join(ROOT, p), encoding='utf-8').read()

def export_list_to_return(src):
    """Turn the trailing `export { a as B, c };` into `return { B: a, c };`."""
    m = list(re.finditer(r'export\s*\{([^}]*)\}\s*;?', src))[-1]
    pairs = []
    for part in m.group(1).split(','):
        part = part.strip()
        if not part: continue
        if ' as ' in part:
            local, name = [s.strip() for s in part.split(' as ')]
            pairs.append(f'{name}:{local}')
        else:
            pairs.append(part)
    return src[:m.start()] + 'return{' + ','.join(pairs) + '};' + src[m.end():]

def addon(path):
    """Wrap an examples/jsm add-on so its exports become names in the bundle scope.
    Imports from 'three' come from THREE; relative imports refer to add-ons
    bundled earlier (see ADDONS order)."""
    src = read(path)
    src = re.sub(r"import\s*\{([^}]*)\}\s*from\s*['\"]three['\"]\s*;", r'const {\1} = THREE;', src)
    src = re.sub(r"import\s*\{[^}]*\}\s*from\s*['\"]\.{1,2}/[^'\"]+['\"]\s*;", '', src)
    names = re.findall(r'^export\s+(?:function|class|const|let)\s+([A-Za-z_$][\w$]*)', src, flags=re.M)
    for m in re.finditer(r'export\s*\{([^}]*)\}', src):
        names += [n.split(' as ')[-1].strip() for n in m.group(1).split(',') if n.strip()]
    names = list(dict.fromkeys(names))
    src = re.sub(r'^export\s+(?=(function|class|const|let)\b)', '', src, flags=re.M)
    src = re.sub(r'export\s*\{[^}]*\}\s*;?', '', src)
    return f"const {{{', '.join(names)}}} = (function(){{\n{src}\nreturn {{{', '.join(names)}}};\n}})();\n"

# dependency order matters
ADDONS = ['RoomEnvironment', 'RoundedBoxGeometry', 'BufferGeometryUtils',
          'Pass', 'CopyShader', 'OutputShader', 'SimplexNoise', 'GTAOShader', 'PoissonDenoiseShader',
          'ShaderPass', 'MaskPass', 'EffectComposer', 'RenderPass', 'OutputPass', 'GTAOPass']

three = export_list_to_return(read('vendor/three.module.min.js'))

from PIL import Image
im = Image.open(os.path.join(ROOT, 'logo.png')).convert('RGBA'); im.thumbnail((256, 256))
buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
logo_uri = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()

hero = read('hero3d.js')
hero = re.sub(r"^import[^;]*;\s*$", '', hero, flags=re.M)
assert "logoImg.src = 'logo.png';" in hero
hero = hero.replace("logoImg.src = 'logo.png';", f"logoImg.src = '{logo_uri}';")

out = ('/* Generated by tools/build-hero.py from hero3d.js — edit the source, then rebuild. */\n'
       '(function(){\n"use strict";\n'
       'const THREE = (function(){\n' + three + '\n})();\n'
       + ''.join(addon(f'vendor/{n}.js') for n in ADDONS)
       + hero + '\n})();\n')
open(os.path.join(ROOT, 'hero3d.bundle.js'), 'w', encoding='utf-8').write(out)
print(f'hero3d.bundle.js written ({len(out) // 1024} KB)')
